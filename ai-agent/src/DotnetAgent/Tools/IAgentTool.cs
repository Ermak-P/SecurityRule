using System.Text.Json;
using DotnetAgent.Models;

namespace DotnetAgent.Tools;

/// <summary>
/// Интерфейс для всех инструментов агента.
///
/// Инструмент (Tool) — это функция которую LLM может запросить выполнить.
/// Это ключевая концепция "Agentic AI":
///   LLM сам решает какой инструмент вызвать → мы выполняем → возвращаем результат → LLM анализирует
///
/// Примеры инструментов:
///   - Чтение/запись файлов (FileSystemTools)
///   - Выполнение команд (ShellTools) — в будущих версиях
///   - HTTP запросы к API (HttpTools) — в будущих версиях
///   - Запуск тестов (TestRunnerTools) — в будущих версиях
///   - Работа с Git (GitTools) — в будущих версиях
///
/// Чтобы добавить новый инструмент:
///   1. Создайте класс реализующий этот интерфейс
///   2. Зарегистрируйте его в ToolRegistry через toolRegistry.Register(new MyTool())
///   3. LLM автоматически узнает о новом инструменте через список Tools в запросе
/// </summary>
public interface IAgentTool
{
    /// <summary>
    /// Уникальное имя инструмента.
    ///
    /// Это имя LLM использует для вызова инструмента.
    /// Должно быть на латинице, с подчёркиваниями (snake_case).
    /// Примеры: "read_file", "list_files", "search_in_files"
    /// </summary>
    string Name { get; }

    /// <summary>
    /// Описание что делает инструмент.
    ///
    /// ОЧЕНЬ ВАЖНО написать хорошее описание!
    /// LLM читает это описание чтобы решить — вызывать ли этот инструмент.
    /// Плохое описание = LLM не будет использовать инструмент или использует неправильно.
    ///
    /// Хорошее описание отвечает на вопросы:
    ///   - Что делает инструмент?
    ///   - Когда его использовать?
    ///   - Есть ли ограничения?
    /// </summary>
    string Description { get; }

    /// <summary>
    /// JSON Schema параметров инструмента.
    ///
    /// Описывает какие аргументы принимает инструмент.
    /// LLM использует эту схему чтобы правильно сформировать аргументы при вызове.
    ///
    /// Возвращайте анонимный объект — он будет сериализован в JSON Schema.
    /// Пример:
    /// <code>
    /// return new {
    ///     type = "object",
    ///     properties = new {
    ///         path = new { type = "string", description = "Путь к файлу" }
    ///     },
    ///     required = new[] { "path" }
    /// };
    /// </code>
    /// </summary>
    object Parameters { get; }

    /// <summary>
    /// Выполняет инструмент с переданными аргументами.
    ///
    /// Вызывается агентом когда LLM запросил этот инструмент.
    /// Аргументы приходят в формате JSON от LLM.
    ///
    /// Правила реализации:
    ///   - Никогда не бросайте исключения — возвращайте строку с описанием ошибки
    ///   - Возвращайте понятный результат — LLM будет его читать и анализировать
    ///   - Если файл большой — возвращайте фрагмент, не весь файл целиком
    ///
    /// </summary>
    /// <param name="arguments">
    ///   Аргументы от LLM в формате JsonElement.
    ///   Для чтения используйте: arguments.TryGetProperty("name", out var val)
    /// </param>
    /// <returns>
    ///   Строка с результатом выполнения.
    ///   Будет добавлена в историю разговора как role="tool" и отправлена обратно в LLM.
    /// </returns>
    Task<string> ExecuteAsync(JsonElement arguments);
}

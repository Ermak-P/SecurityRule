namespace DotnetAgent.Config;

/// <summary>
/// Конфигурация агента.
/// Все параметры с разумными значениями по умолчанию.
///
/// В будущих версиях можно добавить загрузку из файла:
///   var config = JsonSerializer.Deserialize&lt;AgentConfig&gt;(File.ReadAllText("agent.json"));
/// </summary>
public class AgentConfig
{
    /// <summary>
    /// URL до API Ollama.
    ///
    /// Если Ollama запущен в Docker на той же машине (docker compose up -d),
    /// то это всегда http://localhost:11434
    ///
    /// Если Ollama запущен на другом компьютере в сети:
    ///   http://192.168.1.100:11434
    /// </summary>
    public string OllamaUrl { get; set; } = "http://localhost:11434";

    /// <summary>
    /// Название языковой модели в Ollama.
    ///
    /// Эта строка должна совпадать с тем что показывает команда:
    ///   docker exec -it ollama ollama list
    ///
    /// РЕКОМЕНДУЕМЫЕ МОДЕЛИ для работы с кодом:
    ///
    ///   qwen2.5-coder:7b   — рекомендуется для старта
    ///     RAM: ~5 GB | Качество: хорошее | Tool Calling: да
    ///     Команда: docker exec -it ollama ollama pull qwen2.5-coder:7b
    ///
    ///   qwen2.5-coder:14b  — лучше качество генерации кода
    ///     RAM: ~9 GB | Качество: очень хорошее | Tool Calling: да
    ///     Команда: docker exec -it ollama ollama pull qwen2.5-coder:14b
    ///
    ///   llama3.2:3b        — быстрая и лёгкая, подходит для слабых машин
    ///     RAM: ~2.5 GB | Качество: среднее | Tool Calling: да
    ///     Команда: docker exec -it ollama ollama pull llama3.2:3b
    ///
    ///   codellama:7b       — специализирована для кода, альтернатива qwen
    ///     RAM: ~5 GB | Качество: хорошее | Tool Calling: ограниченно
    ///     Команда: docker exec -it ollama ollama pull codellama:7b
    ///
    /// ВАЖНО: модель должна поддерживать "tool calling" (function calling)!
    /// Без этого агент не сможет вызывать инструменты.
    /// </summary>
    public string ModelName { get; set; } = "qwen2.5-coder:7b";

    /// <summary>
    /// Абсолютный путь до .NET проекта на жёстком диске.
    ///
    /// Агент будет иметь доступ ТОЛЬКО к файлам внутри этой директории.
    /// Это предотвращает случайное изменение файлов за пределами проекта.
    ///
    /// Пример: "C:\Projects\MyWebApp"
    /// </summary>
    public string ProjectPath { get; set; } = "";

    /// <summary>
    /// Максимальное количество вызовов инструментов за один запрос.
    ///
    /// Защита от бесконечного цикла: если LLM вызывает инструменты
    /// слишком много раз подряд — агент прерывает выполнение.
    ///
    /// Для большинства задач достаточно 5-10 вызовов.
    /// Увеличьте если агенту нужно обработать много файлов.
    /// </summary>
    public int MaxToolCallsPerRequest { get; set; } = 10;

    /// <summary>
    /// Температура генерации (0.0 — 1.0).
    ///
    /// Контролирует "случайность" ответов модели:
    ///   0.0 — детерминированный, всегда одинаковый ответ
    ///   0.1 — рекомендуется для кода (предсказуемый, но не роботизированный)
    ///   0.7 — творческий (для текстов, идей)
    ///   1.0 — максимально случайный
    ///
    /// Для генерации кода рекомендуется 0.0–0.2
    /// </summary>
    public float Temperature { get; set; } = 0.1f;

    /// <summary>
    /// Размер контекстного окна в токенах.
    ///
    /// Определяет сколько текста модель может "помнить" за один раз.
    /// Один токен ≈ 4 символа.
    ///
    ///   4096  — минимум, для простых задач
    ///   8192  — рекомендуется (по умолчанию)
    ///   16384 — для работы с большими файлами (требует больше RAM)
    ///   32768 — максимум для большинства моделей
    ///
    /// ВНИМАНИЕ: большой контекст требует больше RAM!
    /// </summary>
    public int ContextWindowSize { get; set; } = 8192;
}
